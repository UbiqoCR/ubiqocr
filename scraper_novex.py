def limpiar_precio(texto):
    if not texto:
        return None
    primera = texto.strip().split("\n")[0].strip()
    limpio = re.sub(r"[^\d.,]", "", primera)
    if not limpio:
        return None
    tiene_punto = "." in limpio
    tiene_coma  = "," in limpio
    if tiene_punto and tiene_coma:
        if limpio.rfind(".") > limpio.rfind(","):
            limpio = limpio.replace(",", "")
        else:
            limpio = limpio.replace(".", "").replace(",", ".")
    elif tiene_punto:
        partes = limpio.split(".")
        if len(partes) >= 2 and len(partes[-1]) == 3:
            limpio = limpio.replace(".", "")
        elif len(partes) > 2:
            limpio = limpio.replace(".", "")
    elif tiene_coma:
        partes = limpio.split(",")
        if len(partes) == 2 and len(partes[1]) == 3:
            limpio = limpio.replace(",", "")
        else:
            limpio = limpio.replace(",", ".")
    try:
        r = float(limpio)
        return r if r > 0 else None
    except ValueError:
        return None


def limpiar_texto(s):
    if not isinstance(s, str):
        return s
    return re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", s).strip()


async def extraer_productos(page, cat_nombre, vistos):
    nuevos = []
    try:
        items = await page.query_selector_all("h4.pc__name")
        for item in items:
            try:
                nombre = limpiar_texto((await item.inner_text()).strip())
                if not nombre or len(nombre) < 3:
                    continue
                precio = None
                try:
                    contenedor = await item.evaluate_handle(
                        "el => el.closest('.productCardGrid') || el.closest('[class*=responsiveContainer]') || el.parentElement.parentElement"
                    )
                    precio_el = await contenedor.query_selector(".pc__listPrice__info")
                    if precio_el:
                        precio_txt = (await precio_el.inner_text()).strip()
                        precio = limpiar_precio(precio_txt)
                except Exception:
                    pass
                href = ""
                try:
                    JS = 'el => { let p = el; for(let i=0;i<6;i++){ p=p.parentElement; if(!p) break; let a=p.querySelector("a[href*=\"/producto/\"]"); if(a) return a.href; } return ""; }'
                    href = await item.evaluate(JS)
                    href = limpiar_texto(href)
                except Exception:
                    pass
                clave = href if href else nombre.lower()
                if clave in vistos:
                    continue
                vistos.add(clave)
                nuevos.append({
                    "nombre":    nombre,
                    "precio":    precio,
                    "moneda":    "CRC",
                    "categoria": cat_nombre,
                    "url":       href,
                })
            except Exception:
                continue
    except Exception:
        pass
    return nuevos


